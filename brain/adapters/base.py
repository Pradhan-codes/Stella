"""Abstract LLM Adapter interface and core domain models.

Defines standardized data contracts for communicating with local language models,
including message structures, generation parameters, streaming chunks, and
categorized adapter errors.

CRITICAL ARCHITECTURAL CONSTRAINTS:
1. Pure domain abstraction: LLMAdapter decouples the conversation engine from specific backends.
2. Unvalidated model output: Output text is strictly untrusted and must be validated downstream.
3. No hidden chain-of-thought: Streaming chunks explicitly exclude unvalidated thought deltas.
"""

from abc import ABC, abstractmethod
from enum import Enum
from typing import Iterator, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


class Role(str, Enum):
    """Message roles for chat-based interactions."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class ChatMessage(BaseModel):
    """A single conversational turn message."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    role: Role = Field(
        description="The entity sending the message.",
    )
    content: str = Field(
        description="The text content of the message.",
    )
    name: Optional[str] = Field(
        default=None,
        description="Optional participant or tool name.",
    )


class LLMGenerationParams(BaseModel):
    """Inference parameters for text generation."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    temperature: float = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature. Lower is more deterministic.",
    )
    top_p: float = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling probability threshold.",
    )
    max_tokens: int = Field(
        default=512,
        ge=1,
        le=4096,
        description="Maximum tokens allowed for model completion.",
    )
    stop_sequences: List[str] = Field(
        default_factory=list,
        description="Optional stop sequences that halt generation.",
    )
    format_json: bool = Field(
        default=True,
        description="Whether to enforce structured JSON output format in the backend.",
    )
    repeat_penalty: float = Field(
        default=1.1,
        ge=0.0,
        le=2.0,
        description="Repetition penalty applied to discourage repetitive loops.",
    )


class LLMChunk(BaseModel):
    """A streaming text delta emitted during token generation.

    CRITICAL ARCHITECTURAL NOTICE:
    In accordance with Stella Phase 3 specifications, this contract explicitly
    omits 'thought_delta'. Internal or hidden chain-of-thought tokens must never
    be exposed or streamed unvalidated.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    delta_text: str = Field(
        default="",
        description="Incremental text generated in this streaming chunk.",
    )
    finish_reason: Optional[Literal["stop", "length", "tool_calls", "cancelled", "error"]] = Field(
        default=None,
        description="Reason generation terminated, if this is the final chunk.",
    )
    prompt_tokens: Optional[int] = Field(
        default=None,
        description="Exact prompt tokens evaluated, if reported by engine.",
    )
    completion_tokens: Optional[int] = Field(
        default=None,
        description="Exact completion tokens generated, if reported by engine.",
    )


class LLMResponse(BaseModel):
    """Complete non-streaming result returned from a generation turn."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    content: str = Field(
        description="Full text generated by the model.",
    )
    finish_reason: str = Field(
        default="stop",
        description="Reason generation completed (e.g. stop, length).",
    )
    prompt_tokens: Optional[int] = Field(
        default=None,
        description="Number of tokens in the prompt evaluated by the engine.",
    )
    completion_tokens: Optional[int] = Field(
        default=None,
        description="Number of tokens generated in the completion.",
    )
    total_duration_ms: Optional[float] = Field(
        default=None,
        ge=0.0,
        description="Total duration of inference turn in milliseconds.",
    )
    model: Optional[str] = Field(
        default=None,
        description="Model identifier that processed the request.",
    )


LLMErrorCategory = Literal[
    "ENGINE_OFFLINE",
    "TIMEOUT",
    "OUT_OF_VRAM",
    "CONTEXT_OVERFLOW",
    "MALFORMED_RESPONSE",
    "MODEL_NOT_FOUND",
    "INVALID_REQUEST",
    "CONNECTION_ERROR",
]


class LLMAdapterError(Exception):
    """Base exception for all LLM adapter operational failures."""

    def __init__(
        self,
        category: LLMErrorCategory,
        message: str,
        status_code: Optional[int] = None,
    ):
        super().__init__(f"[{category}] {message}")
        self.category = category
        self.message = message
        self.status_code = status_code


class LLMAdapter(ABC):
    """Abstract interface defining required capabilities of an LLM backend adapter."""

    @abstractmethod
    def ping(self) -> bool:
        """Probe the engine health. Returns True if alive, False otherwise."""

    @abstractmethod
    def check_model_available(self, model_name: Optional[str] = None) -> bool:
        """Check if the specified model (or configured default) is installed locally.

        Never attempts to automatically pull, download, or switch models.
        """

    @abstractmethod
    def generate(
        self,
        messages: List[ChatMessage],
        params: Optional[LLMGenerationParams] = None,
    ) -> LLMResponse:
        """Execute a complete, non-streaming generation turn.

        Args:
            messages: List of formatted chat turns.
            params: Optional generation parameters.

        Returns:
            LLMResponse containing generated text and token metrics.

        Raises:
            LLMAdapterError: On connection failure, timeout, or model errors.
        """

    @abstractmethod
    def stream(
        self,
        messages: List[ChatMessage],
        params: Optional[LLMGenerationParams] = None,
    ) -> Iterator[LLMChunk]:
        """Execute a streaming generation turn, yielding incremental chunks.

        Args:
            messages: List of formatted chat turns.
            params: Optional generation parameters.

        Yields:
            LLMChunk instances as tokens are received.

        Raises:
            LLMAdapterError: On connection failure, timeout, or model errors.
        """

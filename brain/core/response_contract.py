"""Validated Structured Response Contract for Stella Python Brain.

Enforces strict schema validation for model-generated outputs, ensuring
clean separation of user-facing conversational text from typed action proposals
and confirmation requirements.

CRITICAL SECURITY RULE:
This contract explicitly prohibits unvalidated chain-of-thought fields or
hidden thought streaming deltas. All model outputs must be validated through
this schema before downstream presentation or processing.
"""

import json
import re
from typing import Any, Dict, List, Literal, Optional
from uuid import UUID
from pydantic import AliasChoices, BaseModel, ConfigDict, Field, field_validator
from brain.actions.base import ActionRiskLevel

RiskLevel = ActionRiskLevel  # Backward compatibility alias
ExpressionName = Literal["neutral", "happy", "sad", "thinking", "playful", "surprised"]

PLACEHOLDER_REGEX = re.compile(
    r"\[(?:User_?Name|Your\s+Name|Username|User|Name)\]",
    re.IGNORECASE,
)


def sanitize_hallucinated_placeholders(text: str) -> str:
    """Strip hallucinated placeholder tokens like [User_Name], [Your Name], [Name]."""
    if not text:
        return ""
    cleaned = PLACEHOLDER_REGEX.sub("", text)
    cleaned = re.sub(r",\s*([.!?])", r"\1", cleaned)
    cleaned = re.sub(r"\s+([.!?])", r"\1", cleaned)
    cleaned = re.sub(r" {2,}", " ", cleaned).strip()
    return cleaned


class ActionProposalPayload(BaseModel):
    """Represents a proposed action generated by the reasoning engine.

    CRITICAL SECURITY NOTICE:
    A model-provided 'risk_level' is strictly an untrusted suggestion.
    It does NOT authorize execution or grant system permissions. The independent
    Permission Gateway independently determines the true authorization policy.
    """

    model_config = ConfigDict(extra="forbid")

    proposal_id: UUID = Field(
        description="Unique identifier for this action proposal.",
    )
    action_name: str = Field(
        min_length=1,
        max_length=64,
        description="Name of the proposed tool or action from the authorized registry.",
    )
    parameters: Dict[str, Any] = Field(
        default_factory=dict,
        description="Parameters dictionary conforming to the specific action's schema.",
    )
    intent_summary: str = Field(
        min_length=1,
        max_length=256,
        description="Plain-language human-readable explanation of why this action is proposed.",
    )
    risk_level: ActionRiskLevel = Field(
        default="read_only",
        description="Model-suggested risk tier. Independent gateway verifies actual policy tier.",
    )


class ConfirmationRequirement(BaseModel):
    """Metadata specifying that a proposed action requires explicit user authorization."""

    model_config = ConfigDict(extra="forbid")

    prompt_id: UUID = Field(
        description="Unique identifier for this confirmation prompt.",
    )
    proposal_id: UUID = Field(
        description="Identifier of the specific ActionProposal requiring confirmation.",
    )
    action_name: str = Field(
        description="Name of the action awaiting confirmation.",
    )
    summary: str = Field(
        description="Clear, non-technical explanation presented in the confirmation modal.",
    )
    affected_targets: List[str] = Field(
        default_factory=list,
        description="Target paths, URIs, or entities that will be modified or contacted.",
    )
    parameters_digest: str = Field(
        min_length=64,
        max_length=64,
        description="SHA-256 digest of canonicalized parameters to guarantee argument immutability.",
    )
    risk_level: RiskLevel = Field(
        description="Risk tier requiring confirmation (typically consequential or destructive).",
    )


class StructuredResponse(BaseModel):
    """The canonical, validated structure for all outbound model turns.
    
    Rejects any unmapped or extra fields (e.g., hidden reasoning strings,
    raw chain-of-thought deltas, or arbitrary execution payloads).
    """

    model_config = ConfigDict(extra="forbid", populate_by_name=True)

    user_facing_text: str = Field(
        validation_alias=AliasChoices(
            "user_facing_text",
            "response",
            "message",
            "text",
            "dialogue",
            "reply",
            "content",
            "answer",
        ),
        description="The natural language dialogue presented to the user.",
    )
    proposed_actions: List[ActionProposalPayload] = Field(
        default_factory=list,
        description="Zero or more proposed tool actions requiring gateway evaluation.",
    )
    confirmation_requirements: List[ConfirmationRequirement] = Field(
        default_factory=list,
        description="Zero or more confirmation requirements demanded prior to execution.",
    )
    expression_hint: Optional[ExpressionName] = Field(
        default=None,
        description="Optional blendshape expression tag for the Cantarella avatar.",
    )

    @field_validator("user_facing_text", mode="before")
    @classmethod
    def _sanitize_user_facing_text(cls, v: Any) -> str:
        """Ensure user_facing_text is never a serialized JSON dictionary string."""
        if not isinstance(v, str):
            return str(v)
        cleaned = v.strip()
        if cleaned.startswith("{") and cleaned.endswith("}"):
            try:
                parsed = json.loads(cleaned)
                if isinstance(parsed, dict):
                    for key in (
                        "user_facing_text",
                        "response",
                        "message",
                        "text",
                        "dialogue",
                        "reply",
                        "content",
                        "answer",
                    ):
                        val = parsed.get(key)
                        if isinstance(val, str) and val.strip():
                            return cls._sanitize_user_facing_text(val)
            except Exception:
                pass
        return sanitize_hallucinated_placeholders(cleaned)


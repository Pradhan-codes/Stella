# ============================================================================
# Orchestrator Contracts
# ============================================================================

class OrchestratorTurnStatus(str, Enum):
    """Execution status for a single conversation turn."""

    SUCCESS = "success"
    COMPLETED_WITH_ACTIONS = "completed_with_actions"
    AWAITING_CONFIRMATION = "awaiting_confirmation"
    MODEL_ERROR = "model_error"
    TIMEOUT = "timeout"
    MALFORMED_OUTPUT = "malformed_output"
    CONTEXT_OVERFLOW = "context_overflow"
    BUSY = "busy"
    ERROR = "error"


class OrchestratorResponse(BaseModel):
    """Immutable, typed result returned at the completion of a conversation turn."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    turn_id: str = Field(
        description="Unique UUIDv4 identifying this conversation turn.",
    )
    session_id: str = Field(
        description="Session identifier associated with this turn.",
    )
    status: OrchestratorTurnStatus = Field(
        description="Outcome status of the orchestration turn.",
    )
    user_facing_text: str = Field(
        default="",
        description="Conversational response text presented to the user.",
    )
    expression_hint: Optional[str] = Field(
        default=None,
        description="Avatar expression hint (e.g. neutral, happy, playful, thinking).",
    )
    proposed_actions: List[BaseActionProposal] = Field(
        default_factory=list,
        description="Untrusted action proposals extracted from the model turn.",
    )
    confirmation_prompts: List[UserConfirmationPrompt] = Field(
        default_factory=list,
        description="Confirmation prompts generated by gateway policy for protected actions.",
    )
    recalled_memories_count: int = Field(
        default=0,
        description="Number of long-term memories retrieved and provided in context.",
    )
    estimated_prompt_tokens: int = Field(
        default=0,
        description="Estimated token count of the assembled prompt.",
    )
    completion_tokens: Optional[int] = Field(
        default=None,
        description="Tokens generated in model completion if reported by engine.",
    )
    duration_ms: float = Field(
        ge=0.0,
        description="Total turn execution duration in milliseconds.",
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Sanitized non-sensitive diagnostic message if turn encountered an error.",
    )



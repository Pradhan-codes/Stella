class BrainOrchestrator:
    """Central orchestration engine coordinating context, inference, memory, and actions."""

    def __init__(
        self,
        llm_adapter: Optional[LLMAdapter] = None,
        context_manager: Optional[ContextManager] = None,
        memory_store: Optional[SqliteMemoryStore] = None,
        session_store: Optional[SessionMemoryStore] = None,
        personality_config: Optional[PersonalityConfig] = None,
        permission_gateway: Optional[PermissionGateway] = None,
        fsm: Optional[BrainFSM] = None,
        settings: Optional[BrainSettings] = None,
    ) -> None:
        """Initialize Brain Orchestrator with optional dependency injection.

        Args:
            llm_adapter: LLM backend adapter. Defaults to OllamaAdapter with loopback settings.
            context_manager: Token budget & context manager. Defaults to standard configuration.
            memory_store: Long-term SQLite memory store. Defaults to None (disabled).
            session_store: Default short-term working memory store.
            personality_config: Persona & instruction configuration. Defaults to personality.json.
            permission_gateway: Policy permission gateway. Defaults to standard registry gateway.
            fsm: Primary finite state machine. Defaults to a fresh BrainFSM in STANDBY.
            settings: Runtime settings. Defaults to BrainSettings().
        """
        self.settings = settings or BrainSettings()
        self.context_manager = context_manager or ContextManager(
            budget_settings=self.settings.context_budget
        )
        self.memory_store = memory_store
        self.permission_gateway = (
            permission_gateway
            if permission_gateway is not None
            else PermissionGateway(confirmation_ttl_seconds=self.settings.timeouts.confirmation_ttl_seconds)
        )
        self.personality_config = personality_config or load_personality_config(
            self.settings.personality_file
        )

        # Primary LLM Adapter
        if llm_adapter is not None:
            self.llm_adapter = llm_adapter
        else:
            self.llm_adapter = OllamaAdapter(
                base_url=self.settings.ollama_base_url,
                model_name=self.settings.model_identifier,
                ping_timeout_seconds=self.settings.timeouts.ping_timeout_seconds,
                turn_timeout_seconds=self.settings.timeouts.turn_completion_timeout_seconds,
            )

        # Multi-session state management
        self.default_session_id = "default_session"
        self._session_stores: Dict[str, SessionMemoryStore] = {}
        if session_store is not None:
            self._session_stores[session_store.session_id] = session_store
            self.default_session_id = session_store.session_id

        self._session_fsms: Dict[str, BrainFSM] = {}
        if fsm is not None:
            self._session_fsms[self.default_session_id] = fsm

        self._session_locks: Dict[str, threading.Lock] = {}
        self._global_lock = threading.Lock()

        # Operational timeouts
        self.turn_timeout_seconds = self.settings.timeouts.turn_completion_timeout_seconds

    def _get_session_lock(self, session_id: str) -> threading.Lock:
        """Retrieve or create a re-entrant mutex lock for the specified session."""
        with self._global_lock:
            if session_id not in self._session_locks:
                self._session_locks[session_id] = threading.Lock()
            return self._session_locks[session_id]

    def _get_session_store(self, session_id: str) -> SessionMemoryStore:
        """Retrieve or initialize working memory store for a session."""
        with self._global_lock:
            if session_id not in self._session_stores:
                self._session_stores[session_id] = SessionMemoryStore(
                    max_turns=50,
                    session_id=session_id,
                )
            return self._session_stores[session_id]

    def get_session_store(self, session_id: Optional[str] = None) -> SessionMemoryStore:
        """Retrieve the SessionMemoryStore associated with a session."""
        return self._get_session_store(session_id or self.default_session_id)

    def _get_fsm(self, session_id: str) -> BrainFSM:
        """Retrieve or initialize an FSM for a session."""
        with self._global_lock:
            if session_id not in self._session_fsms:
                fsm = BrainFSM(initial_state=BrainState.OFFLINE)
                fsm.transition_to(BrainState.INITIALIZING, reason="Session wake")
                fsm.transition_to(BrainState.STANDBY, reason="Session ready")
                self._session_fsms[session_id] = fsm
            return self._session_fsms[session_id]

    @property
    def fsm(self) -> BrainFSM:
        """Access primary FSM for the default session."""
        return self._get_fsm(self.default_session_id)

    def get_fsm(self, session_id: Optional[str] = None) -> BrainFSM:
        """Retrieve the FSM associated with a session."""
        return self._get_fsm(session_id or self.default_session_id)

    @staticmethod
    def _extract_json_text(raw_text: str) -> str:
        """Extract structured JSON string from raw model text, stripping markdown code fences."""
        cleaned = raw_text.strip()
        # Check for ```json ... ``` code fences
        match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
        if match:
            return match.group(1).strip()
        # Check for raw JSON object { ... }
        if cleaned.startswith("{") and cleaned.endswith("}"):
            return cleaned
        first_brace = cleaned.find("{")
        last_brace = cleaned.rfind("}")
        if first_brace != -1 and last_brace != -1 and last_brace > first_brace:
            return cleaned[first_brace : last_brace + 1].strip()
        return cleaned

    @staticmethod
    def _extract_conversational_text(raw_text: str) -> str:
        """Extract conversational response text from raw model output or serialized JSON.

        Never returns a raw serialized JSON dictionary string to the user.
        If the text contains JSON, extracts standard conversational keys
        ('user_facing_text', 'response', 'message', 'text', 'dialogue') while
        discarding unvalidated chain-of-thought or metadata fields.
        """
        cleaned = raw_text.strip()
        if not cleaned:
            return ""

        json_candidate = BrainOrchestrator._extract_json_text(cleaned)
        if json_candidate.startswith("{") and json_candidate.endswith("}"):
            try:
                parsed = json.loads(json_candidate)
                if isinstance(parsed, dict):
                    for key in (
                        "user_facing_text",
                        "response",
                        "message",
                        "text",
                        "dialogue",
                        "reply",
                        "content",
                        "answer",
                    ):
                        val = parsed.get(key)
                        if isinstance(val, str) and val.strip():
                            return BrainOrchestrator._extract_conversational_text(val)
                    return ""
            except Exception:
                pass

        return sanitize_hallucinated_placeholders(cleaned)


    def handle_turn(
        self,
        user_message: str,
        session_id: Optional[str] = None,
        perceptual_state: Optional[Dict[str, Any]] = None,
        blocking: bool = True,
        turn_timeout_seconds: Optional[float] = None,
    ) -> OrchestratorResponse:
        """Execute one complete conversation turn synchronously within the safety envelope.

        Coordinates:
        1. Multi-session locking and FSM lifecycle progression.
        2. Context assembly with personality guidelines, long-term memory, and history.
        3. LLM generation via domain adapter.
        4. Structured validation and untrusted action proposal evaluation.
        5. Short-term working memory recording without automatic transcript persistence.

        Args:
            user_message: Natural language prompt text from user.
            session_id: Optional session identifier. Defaults to default session.
            perceptual_state: Optional workspace/system telemetry dict.
            blocking: If True, waits for session lock; if False, returns BUSY on contention.
            turn_timeout_seconds: Optional per-turn deadline.

        Returns:
            OrchestratorResponse with assistant text, turn status, and telemetry.
        """
        turn_id = uuid4()
        active_session_id = session_id or self.default_session_id
        t_turn_start = time.perf_counter()

        # Step 1: Session mutex concurrency protection
        session_lock = self._get_session_lock(active_session_id)
        if blocking:
            timeout = turn_timeout_seconds or self.turn_timeout_seconds
            acquired = session_lock.acquire(blocking=True, timeout=timeout)
        else:
            acquired = session_lock.acquire(blocking=False)

        if not acquired:
            logger.warning("Turn [%s] rejected: session [%s] is busy", turn_id, active_session_id)
            return OrchestratorResponse(
                turn_id=str(turn_id),
                session_id=active_session_id,
                status=OrchestratorTurnStatus.BUSY,
                user_facing_text="A conversation turn is already in progress for this session. Please wait.",
                error_message="Concurrent turn contention: session lock is held by another active turn.",
                duration_ms=(time.perf_counter() - t_turn_start) * 1000.0,
            )

        try:
            return self._execute_turn(
                turn_id=turn_id,
                session_id=active_session_id,
                user_message=user_message,
                perceptual_state=perceptual_state,
                t_turn_start=t_turn_start,
            )
        finally:
            session_lock.release()

    def _execute_turn(
        self,
        turn_id: UUID,
        session_id: str,
        user_message: str,
        perceptual_state: Optional[Dict[str, Any]],
        t_turn_start: float,
    ) -> OrchestratorResponse:
        """Internal turn execution pipeline under session lock."""
        fsm = self._get_fsm(session_id)
        session_store = self._get_session_store(session_id)

        # Ensure FSM is in STANDBY
        if fsm.current_state == BrainState.OFFLINE:
            fsm.transition_to(BrainState.INITIALIZING, reason="Orchestrator wake")
            fsm.transition_to(BrainState.STANDBY, reason="Orchestrator ready")
        elif fsm.current_state == BrainState.ERROR:
            fsm.transition_to(BrainState.STANDBY, reason="Orchestrator reset from error")

        # FSM: STANDBY -> LISTENING
        fsm.transition_to(BrainState.LISTENING, reason="Received user input")
        logger.info("Turn [%s] initiated for session [%s]", turn_id, session_id)

        # --------------------------------------------------------------------
        # 1. Long-Term Memory Recall (Read-Only)
        # --------------------------------------------------------------------
        formatted_memories: List[str] = []
        recalled_count = 0
        if self.memory_store is not None:
            try:
                recall_req = MemoryRecallRequest(query_text=user_message, max_results=5)
                recalled = self.memory_store.recall(recall_req)
                recalled_count = len(recalled)
                formatted_memories = format_for_context(recalled)
                logger.info("Recalled %d long-term memories for turn [%s]", recalled_count, turn_id)
            except Exception as mem_err:
                logger.warning(
                    "Long-term memory recall failed for turn [%s]: %s",
                    turn_id,
                    type(mem_err).__name__,
                )

        # --------------------------------------------------------------------
        # 2. Short-Term History Retrieval
        # --------------------------------------------------------------------
        conversation_history = session_store.to_chat_messages()

        # --------------------------------------------------------------------
        # 3. Context Assembly
        # --------------------------------------------------------------------
        # FSM: LISTENING -> THINKING
        fsm.transition_to(BrainState.THINKING, reason="Context assembly and inference")

        system_prompt = build_system_prompt(self.personality_config)

        try:
            assembled = self.context_manager.assemble_context(
                system_instruction=system_prompt,
                current_user_message=user_message,
                conversation_history=conversation_history,
                long_term_memories=formatted_memories,
                perceptual_state=perceptual_state,
            )
            logger.info(
                "Assembled context: ~%d tokens (%d messages) for turn [%s]",
                assembled.estimated_total_tokens,
                len(assembled.messages),
                turn_id,
            )
        except ContextOverflowError as err:
            logger.warning("Turn [%s] failed with context overflow: %s", turn_id, err.detail)
            if fsm.can_transition_to(BrainState.ERROR):
                fsm.transition_to(BrainState.ERROR, reason="Context overflow")
            if fsm.can_transition_to(BrainState.STANDBY):
                fsm.transition_to(BrainState.STANDBY, reason="Recovery from overflow")

            return OrchestratorResponse(
                turn_id=str(turn_id),
                session_id=session_id,
                status=OrchestratorTurnStatus.CONTEXT_OVERFLOW,
                user_facing_text=(
                    "Your message combined with our current conversation context exceeds the "
                    "available context ceiling. Please try a shorter query or reset the session."
                ),
                recalled_memories_count=recalled_count,
                duration_ms=(time.perf_counter() - t_turn_start) * 1000.0,
                error_message=err.detail,
            )

        # --------------------------------------------------------------------
        # 4. LLM Generation
        # --------------------------------------------------------------------
        generation_params = LLMGenerationParams(
            temperature=0.7,
            max_tokens=min(assembled.max_generation_tokens, 256),
            repeat_penalty=1.1,
            format_json=True,
        )

        try:
            t_infer = time.perf_counter()
            llm_response = self.llm_adapter.generate(
                messages=assembled.messages,
                params=generation_params,
            )
            infer_duration_ms = (time.perf_counter() - t_infer) * 1000.0
            logger.info(
                "LLM inference completed in %.2fms for turn [%s]",
                infer_duration_ms,
                turn_id,
            )
        except LLMAdapterError as err:
            logger.warning("Turn [%s] model error [%s]: %s", turn_id, err.category, err.message)
            if fsm.can_transition_to(BrainState.ERROR):
                fsm.transition_to(BrainState.ERROR, reason=f"Model error: {err.category}")
            if fsm.can_transition_to(BrainState.STANDBY):
                fsm.transition_to(BrainState.STANDBY, reason="Recovery from model error")

            status_map = {
                "TIMEOUT": OrchestratorTurnStatus.TIMEOUT,
                "ENGINE_OFFLINE": OrchestratorTurnStatus.MODEL_ERROR,
                "OUT_OF_VRAM": OrchestratorTurnStatus.MODEL_ERROR,
                "MODEL_NOT_FOUND": OrchestratorTurnStatus.MODEL_ERROR,
            }
            mapped_status = status_map.get(err.category, OrchestratorTurnStatus.ERROR)

            fallback_text = (
                "I'm having a little trouble connecting with my local thought engine right now, "
                "Darling. Please make sure our local Ollama service is active and responsive."
            )
            if err.category == "TIMEOUT":
                fallback_text = (
                    "My reasoning process timed out while preparing our response. "
                    "Let's try that again with a simpler request."
                )

            return OrchestratorResponse(
                turn_id=str(turn_id),
                session_id=session_id,
                status=mapped_status,
                user_facing_text=fallback_text,
                recalled_memories_count=recalled_count,
                estimated_prompt_tokens=assembled.estimated_total_tokens,
                duration_ms=(time.perf_counter() - t_turn_start) * 1000.0,
                error_message=err.message,
            )
        except Exception as err:
            logger.warning("Turn [%s] unexpected exception: %s", turn_id, type(err).__name__)
            if fsm.can_transition_to(BrainState.ERROR):
                fsm.transition_to(BrainState.ERROR, reason=f"Inference exception: {type(err).__name__}")
            if fsm.can_transition_to(BrainState.STANDBY):
                fsm.transition_to(BrainState.STANDBY, reason="Recovery from exception")

            return OrchestratorResponse(
                turn_id=str(turn_id),
                session_id=session_id,
                status=OrchestratorTurnStatus.ERROR,
                user_facing_text="An unexpected internal error occurred during reasoning.",
                recalled_memories_count=recalled_count,
                estimated_prompt_tokens=assembled.estimated_total_tokens,
                duration_ms=(time.perf_counter() - t_turn_start) * 1000.0,
                error_message=f"Inference error: {type(err).__name__}",
            )

        # --------------------------------------------------------------------
        # 5. Structured Response Parsing
        # --------------------------------------------------------------------
        raw_content = llm_response.content
        extracted_json = self._extract_json_text(raw_content)

        structured: StructuredResponse
        is_malformed = False
        try:
            structured = StructuredResponse.model_validate_json(extracted_json)
        except Exception as parse_err:
            logger.info("Turn [%s] output is non-JSON or schema mismatch; extracting dialogue", turn_id)
            is_malformed = True
            extracted_text = self._extract_conversational_text(raw_content)
            expr_hint = None
            try:
                parsed_raw = json.loads(self._extract_json_text(raw_content))
                if isinstance(parsed_raw, dict):
                    hint_val = parsed_raw.get("expression_hint")
                    if hint_val in ("neutral", "happy", "sad", "thinking", "playful", "surprised"):
                        expr_hint = hint_val
            except Exception:
                pass

            structured = StructuredResponse(
                user_facing_text=extracted_text or "I hear you, Darling.",
                proposed_actions=[],
                confirmation_requirements=[],
                expression_hint=expr_hint or "neutral",
            )

        # --------------------------------------------------------------------
        # 6. Untrusted Action Proposal Evaluation (No Automatic Dispatch)
        # --------------------------------------------------------------------
        proposals: List[BaseActionProposal] = []
        prompts: List[UserConfirmationPrompt] = []
        has_authorized_actions = False
        has_awaiting_confirmation = False

        for act in structured.proposed_actions:
            # Construct untrusted proposal conforming to BaseActionProposal contract
            prop = BaseActionProposal(
                proposal_id=act.proposal_id,
                turn_id=str(turn_id),
                action_name=act.action_name,
                parameters=act.parameters,
                intent_summary=act.intent_summary,
                risk_level=act.risk_level,
            )
            proposals.append(prop)

            # Evaluate against independent Permission Gateway if configured
            if self.permission_gateway is not None:
                eval_result = self.permission_gateway.evaluate_proposal(prop)
                if eval_result.status == "awaiting_confirmation" and eval_result.prompt is not None:
                    prompts.append(eval_result.prompt)
                    has_awaiting_confirmation = True
                elif eval_result.status == "authorized":
                    has_authorized_actions = True
            else:
                has_authorized_actions = True

        # Determine turn completion status
        if is_malformed and not self._extract_conversational_text(raw_content):
            turn_status = OrchestratorTurnStatus.MALFORMED_OUTPUT
        elif has_awaiting_confirmation:
            turn_status = OrchestratorTurnStatus.AWAITING_CONFIRMATION
        elif has_authorized_actions:
            turn_status = OrchestratorTurnStatus.COMPLETED_WITH_ACTIONS
        else:
            turn_status = OrchestratorTurnStatus.SUCCESS

        # --------------------------------------------------------------------
        # 7. FSM Progression to Output & Standby
        # --------------------------------------------------------------------
        if has_awaiting_confirmation and fsm.can_transition_to(BrainState.AWAITING_CONFIRMATION):
            fsm.transition_to(
                BrainState.AWAITING_CONFIRMATION,
                reason="Consequential action awaiting confirmation",
            )
            fsm.transition_to(BrainState.SPEAKING, reason="Presenting dialogue and confirmation prompt")
        else:
            fsm.transition_to(BrainState.SPEAKING, reason="Presenting assistant dialogue")

        fsm.transition_to(BrainState.STANDBY, reason="Turn complete")

        # --------------------------------------------------------------------
        # 8. Update Short-Term Working Memory
        # --------------------------------------------------------------------
        # Rule: Only update ephemeral short-term memory upon valid turn generation.
        # NEVER write conversation transcripts to durable long-term storage automatically.
        session_store.add_turn(
            ConversationTurn(
                turn_id=turn_id,
                role=Role.USER,
                content=user_message,
            )
        )
        session_store.add_turn(
            ConversationTurn(
                turn_id=uuid4(),
                role=Role.ASSISTANT,
                content=structured.user_facing_text,
                expression_hint=structured.expression_hint,
            )
        )

        total_duration_ms = (time.perf_counter() - t_turn_start) * 1000.0
        logger.info(
            "Turn [%s] completed with status '%s' in %.2fms",
            turn_id,
            turn_status.value,
            total_duration_ms,
        )

        return OrchestratorResponse(
            turn_id=str(turn_id),
            session_id=session_id,
            status=turn_status,
            user_facing_text=structured.user_facing_text,
            expression_hint=structured.expression_hint,
            proposed_actions=proposals,
            confirmation_prompts=prompts,
            recalled_memories_count=recalled_count,
            estimated_prompt_tokens=assembled.estimated_total_tokens,
            completion_tokens=llm_response.completion_tokens,
            duration_ms=total_duration_ms,
        )

    # Convenience method alias
    process_turn = handle_turn


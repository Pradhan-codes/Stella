"""Central Brain Orchestrator for Stella Python Brain (Phase 3 Step 3.6).

Connects the foundation components into a safe, testable, end-to-end conversational turn pipeline:
- Context assembly (personality, recalled long-term memories, recent short-term turns, perception).
- LLM inference via the domain adapter contract (local Ollama or injected test adapters).
- Structured response parsing and validation.
- Non-intrusive action proposal evaluation via the independent Permission Gateway.
- Ephemeral short-term memory maintenance and strictly isolated multi-session concurrency.
- Deterministic FSM lifecycle state transitions with automatic error recovery.

CRITICAL SECURITY AND RELIABILITY INVARIANTS:
1. Untrusted Model Output: LLM responses are data only, never executable instructions.
2. No Automatic Action Execution: Proposed actions are evaluated by policy but NEVER dispatched
   automatically by the orchestrator. Dispatch remains behind the Permission Gateway and user confirmation.
3. No Token Leakage: The orchestrator never requests, receives, or exposes single-use confirmation tokens.
4. Memory Veracity: Full conversation transcripts are NEVER automatically committed to durable long-term storage.
   Only ephemeral short-term working memory is updated.
5. Strict Session Isolation: Concurrent turns for the same session are serialized or rejected via mutex locks;
   different sessions maintain isolated short-term memory and FSM instances.
6. Zero Logging Leakage: Raw user prompts, memory contents, credentials, and full model responses
   are strictly excluded from log records.
"""

